// Generates js/icons.js from open icon sets so the app ships only the icons it uses.
//   Division and unit silhouettes: Game-icons.net (CC BY 3.0, https://game-icons.net)
//   Interface icons: Lucide (ISC, https://lucide.dev)
// Run: node tools/build-icons-js.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const game = require('@iconify-json/game-icons/icons.json'), lucide = require('@iconify-json/lucide/icons.json');

const UNITS = { inf: 'brodie-helmet', arm: 'tank', art: 'field-gun', cav: 'horse-head', mtn: 'peaks', mot: 'jeep', mar: 'anchor', grd: 'imperial-crown', ship: 'battleship', air: 'airplane', port: 'anchor', naval: 'anchor', airbase: 'airplane-departure', hub: 'wooden-crate', refinery: 'oil-pump', fort: 'castle', fire: 'small-fire', battle: 'crossed-swords' };
const UI = {
  flag: 'flag', map: 'map', book: 'scroll-text', mic: 'mic', layers: 'layers', locate: 'locate-fixed', plus: 'plus', minus: 'minus', x: 'x', chev: 'chevron-right', back: 'chevron-left', check: 'check',
  trash: 'trash-2', edit: 'pencil', share: 'share', play: 'play', pause: 'pause', target: 'crosshair', medal: 'medal', flame: 'flame', factory: 'factory', plane: 'plane', anchor: 'anchor',
  arrowR: 'arrow-right', arrowL: 'arrow-left', ring: 'circle-dot', bomb: 'bomb', fort: 'castle', box: 'package', shield: 'shield', crown: 'crown', gear: 'settings', terrain: 'mountain-snow',
  user: 'user-round', info: 'info', down: 'download', up: 'upload', swords: 'swords', handshake: 'handshake', eye: 'eye', snow: 'snowflake', train: 'train-track', users: 'users-round', parachute: 'send', gift: 'gift', megaphone: 'megaphone', search: 'search', clock: 'loader', image: 'image', newspaper: 'newspaper', calendar: 'calendar-days', volume: 'volume-2', mute: 'volume-x', star: 'star', sparkles: 'sparkles', award: 'award', listchecks: 'list-checks', zap: 'zap', chevup: 'chevrons-up', keyboard: 'keyboard', bell: 'bell',
};
const FILLED = { tank: 'tank' }; // game-icons used as interface icons

const get = (set, n) => set.icons[n] || (set.aliases?.[n] && set.icons[set.aliases[n].parent]);
const paths = body => [...body.matchAll(/ d="([^"]+)"/g)].map(m => m[1]).join(' ');
const out = { units: {}, ui: {}, filled: {} };
for (const [k, n] of Object.entries(UNITS)) { if (!get(game, n)) throw new Error('missing game icon ' + n); out.units[k] = paths(get(game, n).body); }
for (const [k, n] of Object.entries(UI)) { if (!get(lucide, n)) throw new Error('missing lucide icon ' + n); out.ui[k] = get(lucide, n).body; }
for (const [k, n] of Object.entries(FILLED)) out.filled[k] = paths(get(game, n).body);

fs.writeFileSync(new URL('../js/icons.js', import.meta.url), `// Generated by tools/build-icons-js.mjs — do not edit.
// Unit silhouettes: Game-icons.net, CC BY 3.0 (https://game-icons.net). Interface icons: Lucide, ISC (https://lucide.dev).
export const UNIT_PATHS = ${JSON.stringify(out.units)};
export const UI_ICONS = ${JSON.stringify(out.ui)};
export const FILLED_ICONS = ${JSON.stringify(out.filled)};
`);
console.log('icons.js', Object.keys(out.units).length, 'unit,', Object.keys(out.ui).length, 'ui');
