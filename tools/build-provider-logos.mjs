// Generates js/provider-logos.js: the brand marks of the model providers the app names in Settings, so it ships only
// the few paths it uses. The marks come from Simple Icons (CC0 1.0, https://simpleicons.org); each is one path on a
// 24 × 24 grid, drawn by the app in the ink of whatever holds it. Names and logos belong to their owners and are
// shown only to identify the service (NOTICE.md).
//
// Not every provider is here on purpose:
//   OpenAI  is not in Simple Icons, and its brand terms could not be read from this project (the page refused the fetch).
//   Groq    is not in Simple Icons, and its trademark policy forbids its logo in a UI without a licence
//           (https://groq.com/trademark-policy, read 2026-11-16).
// Both get a neutral Lucide icon in the app (src/parts.jsx). Nothing here is hand-drawn.
// Run: node tools/build-provider-logos.mjs
import fs from 'node:fs';
import * as si from 'simple-icons';

// provider id (server/providers.mjs) → Simple Icons export
const MARKS = { anthropic: 'siAnthropic', gemini: 'siGooglegemini', mistral: 'siMistralai', openrouter: 'siOpenrouter', ollama: 'siOllama', lmstudio: 'siLmstudio' };

const out = {};
for (const [id, name] of Object.entries(MARKS)) {
  const icon = si[name]; if (!icon?.path) throw new Error(`Simple Icons has no ${name}`);
  out[id] = { title: icon.title, path: icon.path };
}
const version = JSON.parse(fs.readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url), 'utf8')).version;
fs.writeFileSync(new URL('../js/provider-logos.js', import.meta.url), `// Generated by tools/build-provider-logos.mjs — do not edit.
// Brand marks from Simple Icons ${version} (CC0 1.0, https://simpleicons.org), one path each on a 24 × 24 grid.
// Names and logos belong to their owners; they are shown to identify the service.
export const PROVIDER_LOGOS = ${JSON.stringify(out)};
`);
console.log('provider-logos.js', Object.keys(out).join(', '), `(simple-icons ${version})`);
